import {afterEach,it,expect,vi} from 'vitest';
import {act,cleanup,fireEvent,render,screen} from '@testing-library/react';
import {DailyStockistEntry} from '../../vendor/foundation-lottery/src/admin/dashboard/sections/DailyStockistEntry';
import type {LotteryWorkspace,LotteryDailyStockistEntryIdentity} from '../../vendor/foundation-lottery/src/admin/models/lotteryAccountingTypes';
const day='2026-11-01',party={id:'stockist',name:'Test stockist',partyType:'STOCKIST',ticketRatePaise:'100'};
const workspace={organization:{tdsRateBps:0},parties:[party],stockistEntries:[],sales:[],draftSales:[]} as unknown as LotteryWorkspace;
afterEach(()=>{cleanup();vi.useRealTimers();localStorage.clear();});
it('does not retry a failed unchanged row forever and retains it for manual retry',async()=>{
 vi.useFakeTimers();vi.setSystemTime(new Date(day+'T10:00:00Z'));
 const save=vi.fn().mockRejectedValue(new Error('Save rejected'));
 render(<DailyStockistEntry organizationId="org" workspace={workspace} onSave={save}/>);
 fireEvent.change(screen.getByLabelText('Test stockist purchase',{exact:true}),{target:{value:'100'}});
 fireEvent.change(screen.getByLabelText('Test stockist morning return',{exact:true}),{target:{value:'20'}});
 await act(async()=>{await vi.advanceTimersByTimeAsync(800);});
 expect(save).toHaveBeenCalledTimes(1);
 expect(screen.getByRole('alert')).toHaveTextContent('Save rejected');
 expect(screen.getByText('Not saved')).toBeInTheDocument();
 await act(async()=>{await vi.advanceTimersByTimeAsync(5000);});
 expect(save).toHaveBeenCalledTimes(1);
 expect(screen.getByLabelText('Test stockist morning return',{exact:true})).toHaveValue('20');
 await act(async()=>{fireEvent.click(screen.getByRole('button',{name:'Save table'}));});
 expect(save).toHaveBeenCalledTimes(2);
 await act(async()=>{await vi.advanceTimersByTimeAsync(5000);});
 expect(save).toHaveBeenCalledTimes(2);
});
it('shows a nonblocking mismatch and saves a stockist return with no seller entry',async()=>{
 vi.useFakeTimers();vi.setSystemTime(new Date(day+'T10:00:00Z'));
 const entry={id:'entry',partyId:'stockist',occurredAt:day,purchaseQuantity:'100',morningReturnQuantity:'20',dayReturnQuantity:'0',eveningReturnQuantity:'0',commissionPaise:'0'};
 const save=vi.fn().mockResolvedValue(entry as unknown as LotteryDailyStockistEntryIdentity);
 const props={organizationId:'org',workspace,onSave:save};
 const view=render(<DailyStockistEntry {...props}/>);
 fireEvent.change(screen.getByLabelText('Test stockist purchase',{exact:true}),{target:{value:'100'}});
 fireEvent.change(screen.getByLabelText('Test stockist morning return',{exact:true}),{target:{value:'20'}});
 await act(async()=>{fireEvent.click(screen.getByRole('button',{name:'Save table'}));});
 expect(save).toHaveBeenCalledWith(expect.objectContaining({purchaseQuantity:'100',morningReturnQuantity:'20'}));
 view.rerender(<DailyStockistEntry {...props} workspace={{...workspace,stockistEntries:[entry]} as unknown as LotteryWorkspace}/>);
 expect(screen.getByLabelText('Return reconciliation')).toHaveAttribute('data-mismatch','true');
 expect(screen.getByText('Mismatch. Stockist entries can still be saved.')).toBeInTheDocument();
 expect(screen.getByRole('button',{name:'Save table'})).toBeEnabled();
});

it('preserves a newer edit made while the earlier save is in flight',async()=>{
 vi.useFakeTimers();vi.setSystemTime(new Date(day+'T10:00:00Z'));
 let complete!:(value:LotteryDailyStockistEntryIdentity)=>void;
 const first=new Promise<LotteryDailyStockistEntryIdentity>(resolve=>{complete=resolve;});
 const save=vi.fn().mockReturnValueOnce(first).mockResolvedValue({id:'entry'});
 render(<DailyStockistEntry organizationId="org" workspace={workspace} onSave={save}/>);
 fireEvent.change(screen.getByLabelText('Test stockist purchase',{exact:true}),{target:{value:'100'}});
 await act(async()=>{await vi.advanceTimersByTimeAsync(800);});
 fireEvent.change(screen.getByLabelText('Test stockist morning return',{exact:true}),{target:{value:'30'}});
 await act(async()=>{await vi.advanceTimersByTimeAsync(800);});
 expect(save).toHaveBeenCalledTimes(1);
 await act(async()=>{complete({id:'entry'} as unknown as LotteryDailyStockistEntryIdentity);await first;});
 await act(async()=>{await vi.advanceTimersByTimeAsync(800);});
 expect(save).toHaveBeenCalledTimes(2);
 expect(save.mock.calls[1][0]).toMatchObject({purchaseQuantity:'100',morningReturnQuantity:'30'});
 expect(screen.getByLabelText('Test stockist morning return',{exact:true})).toHaveValue('30');
 expect(screen.getByText('Saved',{exact:true})).toBeInTheDocument();
 await act(async()=>{await vi.advanceTimersByTimeAsync(4000);});
 expect(save).toHaveBeenCalledTimes(2);
});
