import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { LotteryAccountingWorkspace } from '../../vendor/foundation-lottery/src/admin/dashboard/sections/LotteryAccountingWorkspace';
import type { LotteryAccountingClient } from '../../vendor/foundation-lottery/src/admin/models/lotteryAccountingClient';
import { runLottery } from './service';
let state:unknown={};
const owner='11111111-1111-7111-8111-111111111111';
async function execute(method:string,payload:Record<string,unknown>={}) {
 const result=await runLottery(state,{method,payload,operationId:crypto.randomUUID()},owner,()=>new Date('2026-10-30T10:00:00Z'));
 state=JSON.parse(JSON.stringify(result.state));return result.result;
}
afterEach(()=>{cleanup();vi.restoreAllMocks();localStorage.clear();sessionStorage.clear();state={};});
it('saves expense opening through the actual master form, restores it, and cancels a correction without writing',async()=>{
 const organization=await execute('createOrganization',{name:'Opening fixture'});
 const category=await execute('createExpenseCategory',{organizationId:organization.id,name:'Home Expenses'});
 await execute('createExpenseProfile',{organizationId:organization.id,categoryId:category.id,name:'Existing person',usualAmountPaise:'0',scheduleType:'ONE_TIME'});
 const update=vi.fn(async(profileId:string,payload:Record<string,unknown>)=>{await execute('updateExpenseProfile',{...payload,profileId});});
 const create=vi.fn(async(payload:Record<string,unknown>)=>{await execute('createExpenseProfile',payload);});
 const api={listOrganizations:()=>execute('listOrganizations'),loadWorkspace:(organizationId:string)=>execute('getWorkspace',{organizationId}),updateExpenseProfile:update,createExpenseProfile:create} as unknown as LotteryAccountingClient;
 const confirm=vi.spyOn(window,'confirm').mockReturnValue(true);
 render(<LotteryAccountingWorkspace api={api} localStore={null} localScope={{ownerKind:'PUBLIC_USER',ownerId:owner}}/>);
 fireEvent.click(await screen.findByRole('button',{name:'Masters'}));
 fireEvent.click(screen.getByRole('button',{name:'Expenses'}));
 fireEvent.click(await screen.findByRole('button',{name:'Existing person'}));
 expect(screen.getByLabelText('Opening balance amount')).toHaveValue('0.00');
 fireEvent.change(screen.getByLabelText('Opening balance amount'),{target:{value:'250.50'}});
 fireEvent.change(screen.getByLabelText('Opening balance date'),{target:{value:'2026-10-29'}});
 fireEvent.click(screen.getByRole('button',{name:'Save Profile'}));
 await waitFor(()=>expect(update).toHaveBeenCalledTimes(1));
 await waitFor(()=>expect(screen.queryByLabelText('Expense profile name')).toBeNull());
 expect(update.mock.calls[0][1]).toMatchObject({openingBalancePaise:'25050',openingBalanceDate:'2026-10-29'});
 expect(confirm).toHaveBeenCalledTimes(2);
 fireEvent.click(screen.getByRole('button',{name:'Existing person'}));
 expect(screen.getByLabelText('Opening balance amount')).toHaveValue('250.50');
 const previous=JSON.stringify(state);
 fireEvent.change(screen.getByLabelText('Opening balance amount'),{target:{value:'999'}});
 confirm.mockReturnValueOnce(false);
 fireEvent.click(screen.getByRole('button',{name:'Save Profile'}));
 expect(update).toHaveBeenCalledTimes(1);expect(JSON.stringify(state)).toBe(previous);
 confirm.mockReturnValueOnce(true).mockReturnValueOnce(false);
 fireEvent.click(screen.getByRole('button',{name:'Save Profile'}));
 expect(update).toHaveBeenCalledTimes(1);expect(JSON.stringify(state)).toBe(previous);
 fireEvent.click(screen.getByRole('button',{name:'Close'}));
 fireEvent.click(screen.getByRole('button',{name:'+ Add Profile'}));
 expect(screen.getByLabelText('Opening balance amount')).toHaveValue('0.00');
 fireEvent.change(screen.getByLabelText('Expense profile name'),{target:{value:'Advance person'}});
 fireEvent.change(screen.getByLabelText('Opening balance direction'),{target:{value:'advance'}});
 fireEvent.change(screen.getByLabelText('Opening balance amount'),{target:{value:'75'}});
 fireEvent.change(screen.getByLabelText('Opening balance date'),{target:{value:'2026-10-28'}});
 fireEvent.click(screen.getByRole('button',{name:'Save Profile'}));
 await waitFor(()=>expect(create).toHaveBeenCalledTimes(1));
 await waitFor(()=>expect(screen.queryByLabelText('Expense profile name')).toBeNull());
 expect(create.mock.calls[0][0]).toMatchObject({openingBalancePaise:'-7500',openingBalanceDate:'2026-10-28'});
 const workspace=await execute('getWorkspace',{organizationId:organization.id});
 expect(workspace.summary).toMatchObject({operatingResultPaise:'0',expensePaise:'0',netCashFlowPaise:'0'});
 expect(workspace.expenseBills).toEqual([]);expect(workspace.expensePayments).toEqual([]);
});
it('includes PWD alongside cash and bank in the dashboard total without merging its ledger',async()=>{
 const org=await execute('createOrganization',{name:'Funds fixture'});
 const seller=await execute('createParty',{organizationId:org.id,name:'Synthetic seller',partyType:'SELLER',ticketRatePaise:'1000'});
 await execute('recordPayment',{organizationId:org.id,partyId:seller.id,direction:'RECEIPT',occurredAt:'2026-10-29',totalAmountPaise:'3222400',methodSplit:{cashPaise:'1255100',bankPaise:'867300',pwtPaise:'1100000'}});
 const api={listOrganizations:()=>execute('listOrganizations'),loadWorkspace:(organizationId:string)=>execute('getWorkspace',{organizationId})} as unknown as LotteryAccountingClient;
 render(<LotteryAccountingWorkspace api={api} localStore={null} localScope={{ownerKind:'PUBLIC_USER',ownerId:owner}}/>);
 expect(await screen.findByText('₹32,224.00')).toBeInTheDocument();
 const w=await execute('getWorkspace',{organizationId:org.id});expect(w.summary.pwtBalancePaise).toBe('1100000');expect(w.summary.netCashFlowPaise).toBe('2122400');
});
