// @vitest-environment node
import fc from 'fast-check'
import { expect, it } from 'vitest'
import { assembleRecoveryTransfer, type RecoveryTransfer } from './recovery-assembly'

function wire(rows: unknown[], chunkSize = 7, purpose: RecoveryTransfer['purpose'] = 'group') {
  const chunks = rows.map(row => new TextEncoder().encode(JSON.stringify(row)))
  const manifest: RecoveryTransfer = { version: 1, transfer: 'fixture', purpose, scopeKind: 'company', scopeId: 'tenant', epoch: 'e',
    from: purpose === 'group' ? '9' : null, next: purpose === 'group' ? String(9 + rows.length) : '42',
    items: rows.length, bytes: chunks.reduce((n, row) => n + row.length, 0) }
  const read = async (item: number, offset: number) => {
    const row = chunks[item - 1]
    const part = row.subarray(offset, offset + chunkSize)
    const encode = (bytes: Uint8Array) => Array.from(bytes, value => value.toString(16).padStart(2, '0')).join('')
    return { transfer: manifest.transfer, item, offset, nextOffset: offset + part.length, size: row.length,
      sha256: encode(new Uint8Array(await crypto.subtle.digest('SHA-256', row))), hex: encode(part) }
  }
  return { manifest, read }
}

it('reconstructs exact UTF-8 and decimal strings across generated byte boundaries', async () => {
  await fc.assert(fc.asyncProperty(fc.array(fc.integer({ min: 1, max: 1_000_000 }), { minLength: 1, maxLength: 5 }),
    fc.integer({ min: 1, max: 25 }), async (values, chunkSize) => {
      const events = values.map((amount, index) => ({ seq: String(10 + index), change: { amount: String(amount), label: 'হিসাব 📚' } }))
      const { manifest, read } = wire(events, chunkSize)
      expect(await assembleRecoveryTransfer(manifest, manifest, read)).toEqual(events)
    }), { numRuns: 24, seed: 7261 })
})

it('rejects corruption, truncation, wrong scopes and missing group events', async () => {
  const { manifest, read } = wire([{ seq: '10', amount: '10' }, { seq: '11', amount: '20' }])
  await expect(assembleRecoveryTransfer(manifest, { ...manifest, scopeId: 'foreign' }, read)).rejects.toThrow('SYNC_RECOVERY_MANIFEST')
  await expect(assembleRecoveryTransfer({ ...manifest, version: 2 }, manifest, read)).rejects.toThrow('SYNC_RECOVERY_MANIFEST')
  await expect(assembleRecoveryTransfer(manifest, manifest, async (item, offset) => {
    const part = await read(item, offset)
    return item === 1 && offset === 0 ? { ...part, hex: '00' + part.hex.slice(2) } : part
  })).rejects.toThrow('SYNC_RECOVERY_DIGEST')
  await expect(assembleRecoveryTransfer(manifest, manifest, async (item, offset) => {
    if (item === 2) throw new Error('fixture interruption')
    return read(item, offset)
  })).rejects.toThrow('fixture interruption')
  const missing = wire([{ seq: '10' }, { seq: '12' }])
  await expect(assembleRecoveryTransfer(missing.manifest, missing.manifest, missing.read)).rejects.toThrow('SYNC_RECOVERY_GROUP_BOUNDARY')
  expect(await assembleRecoveryTransfer(manifest, manifest, read)).toHaveLength(2)
})

it('rejects invalid cursor ranges and manifests before requesting any fragment', async () => {
  const { manifest } = wire([{ seq: '10' }])
  const read = async () => { throw new Error('unexpected fragment request') }
  for (const fields of [{ transfer: '' }, { epoch: 'old' }, { items: -1 }, { items: 16001 }, { bytes: 16777217 }]) {
    await expect(assembleRecoveryTransfer({ ...manifest, ...fields }, manifest, read))
      .rejects.toThrow('SYNC_RECOVERY_MANIFEST')
  }
  await expect(assembleRecoveryTransfer({ ...manifest, next: '01' }, manifest, read))
    .rejects.toThrow('SYNC_RECOVERY_CURSOR')
  await expect(assembleRecoveryTransfer({ ...manifest, next: '11' }, manifest, read))
    .rejects.toThrow('SYNC_RECOVERY_GROUP_BOUNDARY')
})

it('rejects inconsistent fragment offsets, lengths, and digests', async () => {
  const { manifest, read } = wire([{ seq: '10', amount: '100' }])
  for (const fields of [
    { transfer: 'foreign' }, { item: 2 }, { offset: 1 }, { size: 0 },
    { hex: 'xyz' }, { nextOffset: 1 }, { size: manifest.bytes + 1 }, { sha256: 'invalid' },
  ]) {
    await expect(assembleRecoveryTransfer(manifest, manifest, async (item, offset) => ({
      ...await read(item, offset), ...fields,
    }))).rejects.toThrow('SYNC_RECOVERY_FRAGMENT')
  }
  await expect(assembleRecoveryTransfer(manifest, manifest, async (item, offset) => {
    const part = await read(item, offset)
    return offset === 0 ? part : { ...part, sha256: 'f'.repeat(64) }
  })).rejects.toThrow('SYNC_RECOVERY_FRAGMENT')
  await expect(assembleRecoveryTransfer({ ...manifest, bytes: manifest.bytes + 1 }, manifest, read))
    .rejects.toThrow('SYNC_RECOVERY_MANIFEST')
})
