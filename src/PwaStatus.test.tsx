import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import { PwaStatus } from './PwaStatus'
const native = vi.hoisted(() => vi.fn(() => false))
vi.mock('./native/platform', () => ({ isNativeApp: native }))
afterEach(() => { cleanup(); vi.unstubAllGlobals(); vi.unstubAllEnvs(); native.mockReturnValue(false) })
it('does not install a web worker over the native plugin bridge', () => {
  vi.stubEnv('PROD', true)
  native.mockReturnValue(true)
  const register = vi.fn()
  vi.stubGlobal('navigator', { onLine: false, serviceWorker: { register } })
  render(<PwaStatus language="en" />)
  expect(register).not.toHaveBeenCalled()
  expect(screen.getByRole('status')).toHaveTextContent('Offline')
})
it('shows offline guidance in the selected language and removes it on reconnect', () => {
  vi.stubGlobal('navigator', { onLine: false })
  const view = render(<PwaStatus language="bn" />)
  expect(screen.getByRole('status')).toHaveTextContent('ইন্টারনেট নেই')
  view.rerender(<PwaStatus language="hi" />)
  expect(screen.getByRole('status')).toHaveTextContent('इंटरनेट नहीं')
  view.rerender(<PwaStatus language="en" />)
  expect(screen.getByRole('status')).toHaveTextContent('Offline')
  vi.stubGlobal('navigator', { onLine: true })
  fireEvent(window, new Event('online'))
  expect(screen.queryByRole('status')).toBeNull()
  vi.stubGlobal('navigator', { onLine: false })
  fireEvent(window, new Event('offline'))
  expect(screen.getByRole('status')).toHaveTextContent('Offline')
})
it('registers production caching, announces waiting updates and cleans listeners', async () => {
  vi.stubEnv('PROD', true)
  const worker = Object.assign(new EventTarget(), { state: 'installing' })
  const registration = Object.assign(new EventTarget(), { waiting: null as unknown, installing: worker })
  const register = vi.fn().mockResolvedValue(registration)
  vi.stubGlobal('navigator', { onLine: true, serviceWorker: { controller: {}, register } })
  const { unmount } = render(<PwaStatus language="en" />)
  const { waitFor, act } = await import('@testing-library/react')
  await waitFor(() => expect(register).toHaveBeenCalledWith('/sw.js', { scope: '/', updateViaCache: 'none' }))
  await act(async () => { worker.state = 'installed'; worker.dispatchEvent(new Event('statechange')) })
  expect(screen.getByRole('status')).toHaveTextContent('Update ready')
  fireEvent.click(screen.getByRole('button', { name: 'Dismiss update notice' }))
  expect(screen.queryByRole('status')).not.toBeInTheDocument()
  unmount()
  worker.dispatchEvent(new Event('statechange'))
  vi.unstubAllEnvs()
})
it('reports registration failure without blocking the app', async () => {
  vi.stubEnv('PROD', true)
  vi.stubGlobal('navigator', { onLine: true, serviceWorker: { register: vi.fn().mockRejectedValue(new Error('unavailable')) } })
  render(<PwaStatus language="en" />)
  expect(await screen.findByRole('status')).toHaveTextContent('Offline startup is not ready')
  vi.unstubAllEnvs()
})
