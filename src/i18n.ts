export function readLanguage(): Language {
  try {
    const saved = window.localStorage.getItem(LANGUAGE_KEY)
    if (saved === 'bn' || saved === 'en' || saved === 'hi') return saved
  } catch { /* Blocked localStorage does not block the UI. */ }
  return 'bn'
}
export function saveLanguage(next: Language): void {
  try { window.localStorage.setItem(LANGUAGE_KEY, next) }
  catch { /* Keep selected language for current page. */ }
}
